def _trough_ridge_axis_candidate_records(
    anom: np.ndarray,
    lat,
    lon,
    *,
    mode: str,
    percentile: float,
    min_points: int,
    max_lines: int,
    curvature_percentile: float = 55.0,
    smoothing_sigma: float = 1.0,
    vorticity: np.ndarray | None = None,
) -> list[dict]:
    """Return NMC-style trough/ridge axis candidates.

    This keeps the public helper name and calling convention used by the
    earlier Codex implementation, but the internals use the smoother
    synoptic-scale axis construction from this module.

    Parameters
    ----------
    anom:
        2-D input field.  For backward compatibility this is usually the
        500 hPa zonal anomaly, but the function also works with a height field.
    lat, lon:
        1-D coordinate arrays.
    mode:
        ``"trough"`` or ``"ridge"``.
    percentile:
        Tail percentile of ``anom`` used as a broad candidate gate.  For troughs
        ``20`` means values below P20; for ridges it means values above P80.
    min_points:
        Minimum number of connected grid points in a candidate component.
    max_lines:
        Maximum number of candidates to return.
    curvature_percentile:
        Percentile gate for signed Laplacian/curvature support.
    smoothing_sigma:
        Grid-space Gaussian smoothing sigma used by the compatibility helper.
    vorticity:
        Optional relative vorticity. Positive values support troughs; negative
        values support ridges.

    Returns
    -------
    list[dict]
        Raw candidate dictionaries.  They include only line coordinates and
        scalar metadata; no ``bbox``/extent/mask/polygon geometry is returned, so
        the object cannot be mistaken for a filled area by Web GIS code.
    """
    if mode not in {"trough", "ridge"}:
        raise ValueError("mode must be trough or ridge")
    axis_mode: Mode = "trough" if mode == "trough" else "ridge"

    field, lat_arr, lon_arr, vort = _prepare_lat_lon_field(
        np.asarray(anom, dtype=float), lat, lon, vorticity
    )

    # Keep the old helper's grid-sigma behaviour instead of forcing the full
    # physical-radius smoothing used by detect_trough_ridge().  This makes the
    # helper a safer drop-in replacement for existing calls.
    sigma = max(0.0, float(smoothing_sigma))
    smooth = _nan_gaussian(field, (sigma, sigma)) if sigma > 0 else field.copy()

    cfg = NmcStyleConfig(
        min_sigma_grid=max(0.0, sigma),
        min_points_per_line=max(1, int(min_points)),
        max_lines=max(1, int(max_lines)),
        # Candidate helper should expose candidates, not aggressively remove
        # short systems.  Final filtering is still available in detect_trough_ridge.
        min_length_km=0.0,
        component_percentile=70.0,
        seed_percentile=82.0,
        local_extreme_min_score=0.05,
        curvature_min_score=0.02,
        # Use a gentler line style for raw candidates while keeping the line
        # much smoother than the original grid-snapped candidate axis.
        axis_control_spacing_km=220.0,
        output_points=32,
        spline_smooth_factor=2.2,
        reject_tropical_zonal=False,
    )

    score, maps = _build_score(smooth, lat_arr, lon_arr, cfg, axis_mode, vort)
    valid_mask = _domain_mask(lat_arr, lon_arr, cfg) & np.isfinite(smooth)

    # Backward-compatible broad tail mask.  The old implementation used P20 for
    # troughs and P80 for ridges when percentile=20.
    p = float(np.clip(percentile, 0.0, 100.0))
    tail_q = p if axis_mode == "trough" else 100.0 - p
    threshold_value = _finite_percentile(smooth[valid_mask], tail_q)
    tail_mask = smooth <= threshold_value if axis_mode == "trough" else smooth >= threshold_value

    lap_support = maps["laplacian"] if axis_mode == "trough" else -maps["laplacian"]
    curvature_support = np.maximum(lap_support, 0.0) + 0.25 * np.abs(maps["contour_curvature"])
    curvature_threshold = max(
        0.0,
        _finite_percentile(curvature_support[valid_mask], float(curvature_percentile)),
    )

    domain_score = score[valid_mask & tail_mask & np.isfinite(score)]
    if domain_score.size:
        score_threshold = float(np.nanpercentile(domain_score, max(50.0, min(92.0, 100.0 - p))))
    else:
        score_threshold = _finite_percentile(score[valid_mask], 75.0)

    base = (
        valid_mask
        & tail_mask
        & (score >= score_threshold)
        & (curvature_support >= curvature_threshold)
        & (maps["local_score"] >= cfg.local_extreme_min_score)
    )

    structure = np.ones((3, 3), dtype=bool)
    base = ndimage.binary_opening(base, structure=structure, iterations=1)
    base = ndimage.binary_dilation(base, structure=structure, iterations=1) & valid_mask & tail_mask

    labels, count = ndimage.label(base, structure=structure.astype(int))
    components: list[tuple[np.ndarray, np.ndarray]] = []
    for label_id in range(1, count + 1):
        ys, xs = np.where(labels == label_id)
        if ys.size >= cfg.min_points_per_line:
            components.append((ys, xs))

    # If the signed curvature gate is too strict, fall back to the score-gated
    # tail mask.  This mirrors the old function's anomaly_component_axis fallback
    # while still using the smoother line constructor.
    method = "curvature_component_axis"
    method_detail = "nmc_style_curvature_candidate_axis"
    if not components:
        method = "anomaly_component_axis"
        method_detail = "nmc_style_score_candidate_axis"
        fallback = valid_mask & tail_mask & (score >= _finite_percentile(score[valid_mask & tail_mask], 65.0))
        labels, count = ndimage.label(fallback, structure=structure.astype(int))
        for label_id in range(1, count + 1):
            ys, xs = np.where(labels == label_id)
            if ys.size >= cfg.min_points_per_line:
                components.append((ys, xs))

    candidates: list[dict] = []
    vort_support = None
    if vort is not None:
        vort_support = vort if axis_mode == "trough" else -vort

    for ys, xs in components:
        line = _component_to_line(ys, xs, smooth, lat_arr, lon_arr, score, maps, cfg, axis_mode)
        if line is None:
            continue
        values = field[ys, xs]
        curvature_values = curvature_support[ys, xs]
        vort_mean = None
        if vort_support is not None:
            support_values = vort_support[ys, xs]
            if np.isfinite(support_values).any():
                vort_mean = float(np.nanmean(support_values))
        axis_length_km = float(line["axis_length_km"])
        line_coords = np.asarray(line["coordinates"], dtype=float)
        axis_length_degree = float(
            np.sum(
                np.hypot(
                    np.diff(line_coords[:, 0]),
                    np.diff(line_coords[:, 1]),
                )
            )
        ) if line_coords.shape[0] >= 2 else 0.0
        candidates.append(
            {
                "rank": 0,
                "mode": axis_mode,
                "method": method,
                "method_detail": method_detail,
                "coordinates": line["coordinates"],
                    "point_count": int(ys.size),
                    #"bbox": [],
                # Preserve the old Codex field semantics: axis_length is the
                # simple lon/lat polyline length.  New code should prefer the
                # explicit geodesic value axis_length_km.
                "axis_length": axis_length_degree,
                "axis_length_km": axis_length_km,
                "sinuosity": float(line["sinuosity"]),
                "score_mean": float(line["score_mean"]),
                "score_max": float(line["score_max"]),
                "threshold_value": float(threshold_value),
                "curvature_threshold": float(curvature_threshold),
                "curvature_mean": float(np.nanmean(curvature_values)),
                "vorticity_support_mean": vort_mean,
                "min_value": float(np.nanmin(values)),
                "max_value": float(np.nanmax(values)),
                "mean_value": float(np.nanmean(values)),
            }
        )

    # 候选槽/脊线用于业务出图时，应优先保留天气尺度的连续轴线，
    # 不能让紧凑但很深的小低涡因局地 score 高而排到主槽前面。
    candidates.sort(
        key=lambda item: (
            min(float(item["axis_length_km"]), 3000.0) / 3000.0,
            int(item["point_count"]),
            float(item["score_mean"]) * 1.2 + float(item["score_max"]) * 0.4,
        ),
        reverse=True,
    )
    for rank, candidate in enumerate(candidates[: max(1, int(max_lines))], start=1):
        candidate["rank"] = rank
    return candidates[: max(1, int(max_lines))]




def _candidate_record_to_feature(candidate: dict, *, feature_type: str | None = None) -> dict:
    """Convert one raw candidate record into a strict GeoJSON LineString feature.

    The returned object is a valid GeoJSON Feature, but it also carries the old
    scalar fields at the top level as foreign members.  That keeps old endpoint
    code such as ``candidate["threshold_value"]`` from failing when a caller asks
    for GeoJSON output.  Area-like members such as bbox/extent/mask are still
    deliberately omitted.
    """
    mode = str(candidate.get("mode", "trough"))
    feature_type = feature_type or ("trough_candidate" if mode == "trough" else "ridge_candidate")
    title = "500hPa 槽线候选" if mode == "trough" else "500hPa 脊线候选"
    props = {
        "id": f"{feature_type}_{int(candidate.get('rank', 0)):03d}",
        "feature_type": feature_type,
        "candidate_type": "axis_line",
        "title": title,
        "level": "500hPa",
        "rank": int(candidate.get("rank", 0)),
        "mode": mode,
        "method": candidate.get("method"),
        "confidence": 0.70 if "curvature" in str(candidate.get("method", "")) else 0.60,
        "point_count": int(candidate.get("point_count", 0)),
        "axis_length": float(candidate.get("axis_length", 0.0)),
        "axis_length_km": float(candidate.get("axis_length_km", 0.0)),
        "sinuosity": float(candidate.get("sinuosity", 0.0)),
        "score_mean": float(candidate.get("score_mean", 0.0)),
        "score_max": float(candidate.get("score_max", 0.0)),
        "threshold_value": float(candidate.get("threshold_value", np.nan)),
        "curvature_threshold": float(candidate.get("curvature_threshold", np.nan)),
        "curvature_mean": float(candidate.get("curvature_mean", np.nan)),
        "vorticity_support_mean": candidate.get("vorticity_support_mean"),
        "min_value": float(candidate.get("min_value", np.nan)),
        "max_value": float(candidate.get("max_value", np.nan)),
        "mean_value": float(candidate.get("mean_value", np.nan)),
        "evidence": [
            "500hPa 位势高度距平达到尾部分位",
            "候选轴线由综合评分区提取后用主曲线/样条平滑生成",
            "输出为严格 GeoJSON LineString，不携带候选面区域",
        ],
    }
    if props["vorticity_support_mean"] is not None:
        props["evidence"].append("500hPa 相对涡度符号与槽脊性质一致")

    feature = _strict_line_feature(candidate.get("coordinates", []), props)

    # Backward-compatible foreign members.  Some existing service code still
    # reads candidate["threshold_value"], candidate["coordinates"], etc. from
    # the object returned by trough_ridge_axis_candidates().  Keep these scalar
    # fields available without reintroducing bbox/polygon/mask data.
    for key in (
        "rank",
        "mode",
        "method",
        "coordinates",
        "point_count",
        "axis_length",
        "axis_length_km",
        "sinuosity",
        "score_mean",
        "score_max",
        "threshold_value",
        "curvature_threshold",
        "curvature_mean",
        "vorticity_support_mean",
        "min_value",
        "max_value",
        "mean_value",
    ):
        if key in candidate:
            feature[key] = candidate[key]
    return feature


